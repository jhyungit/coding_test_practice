def backtrack(현재_상태):
    # 1. 종료 조건: 완성됐으면 정답 처리하고 되돌아감
    if 목표에_도달했나(현재_상태):
        정답_기록()
        return

    # 2. 이 단계에서 시도할 후보들을 하나씩
    for 선택 in 후보들:
        # 3. 가지치기: 이 선택이 무효면 시도조차 안 함
        if not 유효한가(선택):
            continue

        # 4. 선택한다
        상태에_반영(선택)

        # 5. 그 선택을 안고 다음 단계로 (깊이 우선)
        backtrack(다음_상태)

        # 6. 되돌린다 (다른 선택을 시도하기 위해 원상복구)
        상태에서_제거(선택)